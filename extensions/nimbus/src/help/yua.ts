/** ゆあが参照する Nimbus の説明。機能を足したらここも更新する */
export const NIMBUS_GUIDE = `
# Nimbus とは
Claude Code のエージェントを操縦するためのコックピットを、VS Code（Code - OSS）の上に作った IDE。
Anthropic 非公式・Microsoft 非公式の独立プロジェクト。エディタ・ファイルツリー・SCM・検索・
拡張機能は VS Code のものをそのまま使い、Nimbus はエージェントの操縦に集中している。

# 画面

左のアクティビティバーの雲アイコンが Nimbus。**普段使うものだけを 5 段**置いてある。

- **コックピット**: Claude との会話。Enter で送信、Shift+Enter で改行。
  ヘッダに状態（入力待ち／実行中）とターン数・所要時間・累計コストが出る。
- **タスク**: 並列タスクの板。タスクごとに git worktree を切るので、同じリポジトリで
  複数の Claude を同時に走らせても互いの作業を壊さない。
- **承認待ち**: 判断を待っているツール実行の一覧。
- **レビュー**: 変更を見て印をつけるところ。
- **文脈**: いま Claude に渡っている前提の一覧。課金モード・モデル・作業ディレクトリ・
  権限モード・使えるツール・スキル・スラッシュコマンド・MCP サーバー・CLAUDE.md の階層。
- **ヘルプ（ゆあ）**: ここ。畳んだ状態で一番下にある。

**診断は下部パネル「Nimbus 診断」**にまとめてある（コマンド「Nimbus: 診断パネルを開く」）。
セッションの中身・時系列・使用量・MCP サーバーの 4 つ。

**たまにしか使わないものは、コマンドパレットから開く**（既定では出していない）。
- 「Nimbus: スキル一覧を開く」
- 「Nimbus: CLAUDE.md を開く」
- 「Nimbus: 設定ビューを開く」

- **ステータスバー**（右下）: 承認待ちの件数、実行状態、累計コスト。

# 承認
Claude がツールを使う前に確認ダイアログが出る。ファイルを書き換えるツール（Edit / Write /
MultiEdit）は、**承認する前に差分エディタで変更内容が開く**。実ファイルにはまだ書き込まれていない。
- 「許可」= 今回だけ許可
- 「このセッションでは常に許可」= 以後このセッションでは聞かない
- 「拒否」= 実行させない。ダイアログを Esc で閉じた場合も拒否として扱う
- 設定 nimbus.permissions.autoApproveReadOnly を有効にすると、読み取り専用のツール
  （Read / Glob / Grep など）は確認なしで通る

# タスクと worktree
- 「新しいタスク」でタスク名と最初の指示を入れると、worktree（作業用の別ディレクトリ）と
  ブランチ nimbus/<タスク名> が作られ、そこで Claude が動く
- worktree の実体は ~/.nimbus/worktrees 以下。利用者のリポジトリは汚れない
- 「worktree を開く」で別ウィンドウとして開ける
- 「完了」で worktree を削除するが、**未コミットの成果はブランチへ自動でコミットしてから消す**ので
  作業が失われることはない。ブランチは残るので、あとから通常どおりマージできる
- 設定 nimbus.tasks.maxConcurrent で同時実行数の上限を決める（既定 2）。上限に達したタスクは
  待機し、空きが出ると自動で開始する

# 課金モード
「文脈」とステータスバーに出る。Claude Code のログイン方法で決まる。
- サブスク利用（利用上限を消費）: OAuth ログイン
- API キー利用（従量課金）: API キーを使っている
- 累計コストはセッションごとの積算値

# 設定
- nimbus.claudeCodeExecutable: 使う Claude Code の実行ファイル。空なら PATH や
  ~/.local/bin などから自動で探す
- nimbus.permissions.autoApproveReadOnly / nimbus.permissions.showDiffBeforeApproval
- nimbus.tasks.maxConcurrent

# 拡張機能
Open VSX（open-vsx.org）から取得する。Microsoft の Marketplace は利用規約でフォークからの
利用が認められていないため使えない。Marketplace にしか無い拡張は VSIX を手動で入れる。

# 制約・注意
- 信頼していないフォルダ（制限モード）では **Claude を実行しない**。画面は開くので、
  実行しようとしたときに理由と「このフォルダを信頼する」ボタンが出る。
  Claude はフォルダの中でコマンドを実行しファイルを書き換えるので、中身を確認できている
  フォルダだけで信頼すること
- Nimbus は Claude Code 本体を同梱していない。利用者がインストールしたものを使う
`.trim();

