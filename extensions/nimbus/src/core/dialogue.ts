/**
 * 頼みかたの型（tasks.md T-188 / T-189）。
 *
 * 「複数案を比べたい」「意見が食い違った」は、**中身を持っているのは会話のほう**なので、
 * Claude に書かせるのが早い。ここが持つのは頼みかたの型だけ。
 *
 * 型に何を書くかが本体 — **「まだ変更しないで」「どちらが正しいかを決めつけないで」**と
 * 明示しないと、比べる前に直し始めるし、相違を勝手に決着させてしまう。
 *
 * VS Code に依存しないので単体で検証できる。
 */

/** 選択肢の比較表（T-188） */
export const COMPARE_OPTIONS_PROMPT = [
	'いま検討している実装方針を、**表**にして比べてください。',
	'',
	'- 案は 2〜4 つ。それぞれに「良いところ」「困るところ」「向いている場面」を書く',
	'- 最後に「あなたの推し」と、その理由を 1 行で',
	'- **まだ変更はしないでください。** 選ぶのは私です'
].join('\n');

/**
 * 意見の相違（T-189）。
 * **どちらが正しいかを決めつけさせない** — 決着を急ぐと、後から検証できなくなる。
 */
export function disagreementPrompt(mine: string, theirs: string): string {
	return [
		'いまの私の考えと、あなたの提案が食い違っています。',
		'',
		`私の考え: ${mine}`,
		`あなたの提案の要点: ${theirs}`,
		'',
		'次を書いてください。**どちらが正しいかを決めつけないでください。**',
		'',
		'1. 食い違いの核心（何についての違いか）',
		'2. それぞれが正しくなる条件',
		'3. 後から検証するなら、何を見れば決着がつくか'
	].join('\n');
}
